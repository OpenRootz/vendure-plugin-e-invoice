import gql from 'graphql-tag';

const sharedTypes = `
  enum EInvoiceType {
    INVOICE
    CREDIT_NOTE
  }

  enum EInvoiceFormat {
    ZUGFERD
    XRECHNUNG_CII
    XRECHNUNG_UBL
  }

  type EInvoiceFile {
    id: ID!
    format: EInvoiceFormat!
    fileName: String!
    mimeType: String!
    size: Int!
    "Hex SHA-256 of the content"
    sha256: String!
    "Signed, time-limited download link"
    downloadUrl: String!
  }
`;

export const shopApiExtensions = gql`
  ${sharedTypes}

  "An issued invoice or credit note of the customer's order"
  type EInvoice implements Node {
    id: ID!
    createdAt: DateTime!
    type: EInvoiceType!
    number: String!
    issueDate: String!
    currencyCode: CurrencyCode!
    totalWithTax: Money!
    files: [EInvoiceFile!]!
  }

  extend type Order {
    "Issued invoices and credit notes"
    eInvoices: [EInvoice!]!
  }
`;

