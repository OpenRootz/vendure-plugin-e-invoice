import gql from 'graphql-tag';

export const adminApiExtensions = gql`
  enum EInvoiceType {
    INVOICE
    CREDIT_NOTE
  }

  enum EInvoiceStatus {
    BLOCKED
    PENDING
    ISSUED
    FAILED
    VOID
  }

  enum EInvoiceFormat {
    ZUGFERD
    XRECHNUNG_CII
    XRECHNUNG_UBL
  }

  type EInvoiceIssue {
    code: String!
    message: String!
    path: String
  }

  type EInvoiceFile {
    id: ID!
    format: EInvoiceFormat!
    fileName: String!
    mimeType: String!
    size: Int!
    sha256: String!
  }

  type EInvoice implements Node {
    id: ID!
    createdAt: DateTime!
    updatedAt: DateTime!
    type: EInvoiceType!
    status: EInvoiceStatus!
    reason: String!
    number: String
    issueDate: String
    currencyCode: CurrencyCode!
    totalNet: Money!
    totalTax: Money!
    totalWithTax: Money!
    formats: [EInvoiceFormat!]!
    files: [EInvoiceFile!]!
    issues: [EInvoiceIssue!]!
    errorMessage: String
    voidReason: String
    "Credit notes: the corrected invoice"
    correctedInvoice: EInvoice
    "Invoices: their credit notes (with a number)"
    creditNotes: [EInvoice!]!
    "Invoices: total minus credit notes; 0 for credit notes"
    remainingAmount: Money!
    order: Order!
    orderCode: String!
  }

  type EInvoiceList implements PaginatedList {
    items: [EInvoice!]!
    totalItems: Int!
  }

  # Filter and sort inputs are generated by Vendure
  input EInvoiceListOptions

  input EInvoiceFilterParameter {
    orderCode: StringOperators
  }

  input EInvoiceSortParameter {
    orderCode: SortOrder
  }

  type EInvoicePreview {
    "The ZUGFeRD PDF as a data URL; null if it could not be rendered"
    pdf: String
    "Problems that would block the invoice"
    issues: [EInvoiceIssue!]!
  }

  input EInvoiceCreditNoteLineInput {
    orderLineId: ID!
    quantity: Int!
  }

  input CreateEInvoiceCreditNoteInput {
    invoiceId: ID!
    "Order lines and quantities to credit, at the invoiced prices"
    lines: [EInvoiceCreditNoteLineInput!]
    "Credit shipping and surcharges"
    shipping: Boolean
    "Gross amount to credit in addition, split across the VAT rates of the invoice. Negative = deduction."
    amount: Money
    "Credit everything that has not been credited yet. The other fields are ignored."
    fullReversal: Boolean
    "Printed on the credit note"
    note: String
  }

  type EInvoiceLayout {
    logoAssetId: ID
    accentColor: String
    introText: String
    closingText: String
    footerText: String
  }

  input EInvoiceLayoutInput {
    "PNG, JPEG or SVG asset shown at the top right of the PDF"
    logoAssetId: ID
    "Hex color, e.g. #1a5fb4"
    accentColor: String
    introText: String
    closingText: String
    footerText: String
  }

  type EInvoiceAddress {
    line1: String
    line2: String
    line3: String
    postalCode: String
    city: String
    "ISO 3166-1 alpha-2"
    countryCode: String
    subdivision: String
  }

  input EInvoiceAddressInput {
    line1: String
    line2: String
    line3: String
    postalCode: String
    city: String
    "ISO 3166-1 alpha-2"
    countryCode: String
    subdivision: String
  }

  type EInvoiceContact {
    name: String
    phone: String
    email: String
  }

  input EInvoiceContactInput {
    name: String
    phone: String
    email: String
  }

  type EInvoiceElectronicAddress {
    "e.g. EM (email), 0204 (Leitweg-ID), 9930 (German VAT ID)"
    scheme: String!
    value: String!
  }

  input EInvoiceElectronicAddressInput {
    scheme: String!
    value: String!
  }

  type EInvoiceLegalRegistration {
    id: String!
    scheme: String
  }

  input EInvoiceLegalRegistrationInput {
    "e.g. HRB 12345, Amtsgericht Berlin-Charlottenburg"
    id: String!
    scheme: String
  }

  type EInvoiceBankAccount {
    iban: String!
    bic: String
    accountName: String
  }

  input EInvoiceBankAccountInput {
    iban: String!
    bic: String
    accountName: String
  }

  type EInvoiceSellerSettings {
    name: String
    tradingName: String
    address: EInvoiceAddress
    vatId: String
    taxNumber: String
    legalRegistration: EInvoiceLegalRegistration
    legalInfo: String
    contact: EInvoiceContact
    electronicAddress: EInvoiceElectronicAddress
    bank: EInvoiceBankAccount
  }

  input EInvoiceSellerSettingsInput {
    "BT-27 legal name"
    name: String
    tradingName: String
    address: EInvoiceAddressInput
    "BT-31, e.g. DE123456789"
    vatId: String
    "BT-32 German Steuernummer"
    taxNumber: String
    legalRegistration: EInvoiceLegalRegistrationInput
    "BT-33, e.g. managing directors"
    legalInfo: String
    "BG-6, mandatory in XRechnung"
    contact: EInvoiceContactInput
    "BT-34, where buyers send e-invoices to"
    electronicAddress: EInvoiceElectronicAddressInput
    "For SEPA credit transfer when an amount is due"
    bank: EInvoiceBankAccountInput
  }

  type EInvoicePaymentSettings {
    termsText: String
    termDays: Int
  }

  input EInvoicePaymentSettingsInput {
    "BT-20, e.g. Zahlbar innerhalb von 14 Tagen ohne Abzug."
    termsText: String
    "Days from the issue date to the due date (BT-9)"
    termDays: Int
  }

  type EInvoiceChannelSettings {
    enabled: Boolean!
    autoIssue: Boolean!
    seller: EInvoiceSellerSettings!
    payment: EInvoicePaymentSettings!
    layout: EInvoiceLayout!
  }

  input UpdateEInvoiceChannelSettingsInput {
    enabled: Boolean
    autoIssue: Boolean
    "Replaces the stored seller data"
    seller: EInvoiceSellerSettingsInput
    "Replaces the stored payment settings"
    payment: EInvoicePaymentSettingsInput
    "Replaces the stored layout settings"
    layout: EInvoiceLayoutInput
  }

  extend type Order {
    eInvoices: [EInvoice!]!
  }

  extend type Query {
    eInvoices(options: EInvoiceListOptions): EInvoiceList!
    eInvoice(id: ID!): EInvoice
    eInvoiceChannelSettings: EInvoiceChannelSettings!
    "What is missing before invoices can be issued in this channel (seller data, tax categories, ...)"
    eInvoiceSetupStatus: [EInvoiceIssue!]!
    "Renders the invoice the order would get now, with a draft number. Nothing is saved and no number is used."
    eInvoicePreview(orderId: ID!): EInvoicePreview!
  }

  extend type Mutation {
    "Create the invoice for an order. Returns a BLOCKED invoice with issues if data is missing."
    createEInvoice(orderId: ID!): EInvoice!
    """
    BLOCKED invoice: map the order again. BLOCKED credit note: build it from the refund again; returns null if it is
    no longer needed (e.g. the invoice has been credited in full meanwhile) and was removed. FAILED: render the files again.
    """
    retryEInvoice(id: ID!): EInvoice
    "Credit note for an invoice. The credited quantities and amounts can never exceed the invoice."
    createEInvoiceCreditNote(input: CreateEInvoiceCreditNoteInput!): EInvoice!
    "Credit the invoice in full and issue a new one for the current order (e.g. after correcting the buyer data). Returns the new invoice."
    cancelAndReissueEInvoice(invoiceId: ID!): EInvoice!
    "FAILED document that can never be rendered: the number stays used and the reason documents the gap."
    voidEInvoice(id: ID!, reason: String!): EInvoice!
    updateEInvoiceChannelSettings(input: UpdateEInvoiceChannelSettingsInput!): EInvoiceChannelSettings!
  }
`;
